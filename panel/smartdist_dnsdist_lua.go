package main

import (
	"encoding/json"
	"fmt"
	"strings"
)

// generateDnsdistLua mengubah section dnsdist profil v1 menjadi
// dnsdist-profile.lua. Semua nilai string lewat luaQuote; angka lewat %d dari
// int yang sudah divalidasi. Profil tanpa section -> PROFILE_ENABLED = false.
// Dimuat dnsdist.conf sebelum baseline dibaca; nilai nil = pakai baseline.
func generateDnsdistLua(raw []byte) (string, error) {
	var doc SmartDistProfile
	if err := json.Unmarshal(raw, &doc); err != nil {
		return "", fmt.Errorf("dnsdist: profil JSON tidak valid: %w", err)
	}
	return generateDnsdistLuaFromStruct(&doc)
}

// generateDnsdistLuaFromStruct: generasi dari struct yang sudah di-decode.
func generateDnsdistLuaFromStruct(doc *SmartDistProfile) (string, error) {
	var b strings.Builder
	b.WriteString("-- dnsdist profile v1 (auto-generated by panel agent, do not edit)\n")
	d := doc.Dnsdist
	if d == nil {
		b.WriteString("PROFILE_ENABLED = false\n")
		return b.String(), nil
	}
	if err := validDnsdistSection(d); err != nil {
		return "", err
	}
	b.WriteString("PROFILE_ENABLED = true\n")
	if d.BlockMode != "" {
		fmt.Fprintf(&b, "PROFILE_BLOCK_MODE = %s\n", luaQuote(d.BlockMode))
	}
	if len(d.SinkholeV4) > 0 {
		fmt.Fprintf(&b, "PROFILE_SINKHOLE_V4 = %s\n", luaStrList(d.SinkholeV4))
	}
	if len(d.SinkholeV6) > 0 {
		fmt.Fprintf(&b, "PROFILE_SINKHOLE_V6 = %s\n", luaStrList(d.SinkholeV6))
	}
	// ACL kosong = pakai baseline. Jika diemit {} ACL akan menolak semua query.
	if len(d.ACL) > 0 {
		fmt.Fprintf(&b, "PROFILE_ACL = %s\n", luaStrList(d.ACL))
	}
	// Upstream kosong = pakai baseline. {} akan menghapus semua upstream.
	if len(d.Upstreams) > 0 {
		parts := make([]string, 0, len(d.Upstreams))
		for _, u := range d.Upstreams {
			parts = append(parts, fmt.Sprintf("{name=%s, address=%s, pool=%s}",
				luaQuote(u.Name), luaQuote(u.Address), luaQuote(u.Pool)))
		}
		fmt.Fprintf(&b, "PROFILE_UPSTREAMS = {%s}\n", strings.Join(parts, ", "))
	}
	luaInt(&b, "PROFILE_ECS_V4", d.ECSv4)
	luaInt(&b, "PROFILE_ECS_V6", d.ECSv6)
	luaInt(&b, "PROFILE_MAX_QPS_PER_IP", d.MaxQPSPerIP)
	luaInt(&b, "PROFILE_TCP_MAX_CONNS", d.TCPMaxConns)
	luaInt(&b, "PROFILE_TCP_MAX_QUERIES", d.TCPMaxQueries)
	return b.String(), nil
}

func luaStrList(xs []string) string {
	q := make([]string, 0, len(xs))
	for _, x := range xs {
		q = append(q, luaQuote(x))
	}
	return "{" + strings.Join(q, ", ") + "}"
}

func luaInt(b *strings.Builder, name string, v *int) {
	if v != nil {
		fmt.Fprintf(b, "%s = %d\n", name, *v)
	}
}
